#!/usr/bin/env python3
"""Build launcher icon assets from the SVG sources in src/.

    python3 build.py --res <app>/src/main/res      Android adaptive icon (vector drawables)
    python3 build.py --play <dir>                   512 px Play store icon
    python3 build.py --preview <dir>                masked renders: five shapes, themed, 48 px

Sources are 108x108 viewBox SVGs holding only <path d fill [fill-rule]> elements, so the
conversion to VectorDrawable is one to one. Rendering needs rsvg-convert.
"""
import argparse
import math
import re
import subprocess
from pathlib import Path

SRC = Path(__file__).resolve().parent / "src"
LAYERS = ("background", "foreground", "monochrome")
PATH_RE = re.compile(r"<path\b([^>]*)/>", re.S)
ATTR_RE = re.compile(r'([\w-]+)="([^"]*)"')


def paths(layer):
    out = []
    for m in PATH_RE.finditer((SRC / f"{layer}.svg").read_text()):
        a = dict(ATTR_RE.findall(m.group(1)))
        out.append((a["d"], a.get("fill", "#000000"), a.get("fill-rule", "nonzero")))
    return out


def svg_body(layer, fill=None):
    return "".join(
        f'<path d="{d}" fill="{fill or f}" fill-rule="{r}"/>' for d, f, r in paths(layer))


# Android -----------------------------------------------------------------------------------

def vector(layer):
    rows = []
    for d, fill, rule in paths(layer):
        ftype = ' android:fillType="evenOdd"' if rule == "evenodd" else ""
        rows.append(f'    <path\n        android:fillColor="{fill.upper()}"{ftype}\n'
                    f'        android:pathData="{d}" />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by brand/icon/build.py from brand/icon/src. Do not edit. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            + "\n".join(rows) + "\n</vector>\n")


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by brand/icon/build.py. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


def build_res(res):
    (res / "drawable").mkdir(parents=True, exist_ok=True)
    (res / "mipmap-anydpi-v26").mkdir(parents=True, exist_ok=True)
    for layer in LAYERS:
        (res / "drawable" / f"ic_launcher_{layer}.xml").write_text(vector(layer))
    for name in ("ic_launcher", "ic_launcher_round"):
        (res / "mipmap-anydpi-v26" / f"{name}.xml").write_text(ADAPTIVE)


# Rendering ---------------------------------------------------------------------------------

def render(svg_text, png, width):
    subprocess.run(["rsvg-convert", "-w", str(width), "-o", str(png)],
                   input=svg_text.encode(), check=True)


def build_play(out):
    out.mkdir(parents=True, exist_ok=True)
    # Play applies its own 20% corner radius; ship the full-bleed square, viewport only.
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="72" height="72" viewBox="18 18 72 72">'
           + svg_body("background") + svg_body("foreground") + "</svg>")
    render(svg, out / "play-512.png", 512)


# Launcher masks, drawn in the 72x72 visible viewport (18..90 of the 108 canvas).
def _polar(fn, steps=360):
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        r = fn(t)
        pts.append((54 + r * math.cos(t), 54 + r * math.sin(t)))
    return "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + " Z"


def _superellipse(n=4.0, r=36.0, steps=360):
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        pts.append((54 + r * math.copysign(abs(c) ** (2 / n), c),
                    54 + r * math.copysign(abs(s) ** (2 / n), s)))
    return "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + " Z"


MASKS = {
    "circle": _polar(lambda t: 36),
    "squircle": _superellipse(),
    # every mask keeps the 66 dp safe circle (r 33), as real launchers do
    "cookie": _polar(lambda t: 34.4 + 1.6 * math.cos(7 * (t + math.pi / 2))),
    "clover": _polar(lambda t: 33 + 3 * abs(math.cos(2 * t))),
    "arch": "M18 54 A36 36 0 0 1 90 54 V78 Q90 90 78 90 H30 Q18 90 18 78 Z",
}

# Themed icon tints, roughly what Android 13+ derives from a neutral wallpaper.
THEMES = {
    "colour": None,
    "themed-light": ("#FFE4DA", "#6E2A12"),
    "themed-dark": ("#3B2C27", "#FFD6C8"),
}


def icon_svg(mask, theme, size, x=0, y=0):
    if THEMES[theme] is None:
        body = svg_body("background") + svg_body("foreground")
    else:
        bg, fg = THEMES[theme]
        body = f'<rect width="108" height="108" fill="{bg}"/>' + svg_body("monochrome", fg)
    cid = f"m{mask}{theme}{size}"
    s = size / 72
    return (f'<g transform="translate({x} {y}) scale({s}) translate(-18 -18)">'
            f'<clipPath id="{cid}"><path d="{MASKS[mask]}"/></clipPath>'
            f'<g clip-path="url(#{cid})">{body}</g></g>')


def build_preview(out):
    out.mkdir(parents=True, exist_ok=True)
    big, small, gap, label = 144, 48, 36, 150
    cols = list(MASKS)
    w = label + len(cols) * (big + gap)
    rows = list(THEMES) + ["48px"]
    h = gap + len(rows) * (big + gap)
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}">',
             f'<rect width="{w}" height="{h}" fill="#F4F1EC"/>',
             f'<rect y="{gap + 2 * (big + gap) - gap // 2}" width="{w}" '
             f'height="{2 * (big + gap)}" fill="#24211E"/>']
    font = 'font-family="Roboto, sans-serif" font-size="18"'
    for j, c in enumerate(cols):
        parts.append(f'<text x="{label + j * (big + gap) + big / 2}" y="24" text-anchor="middle" '
                     f'{font} fill="#444">{c}</text>')
    for i, row in enumerate(rows):
        y = gap + i * (big + gap)
        ink = "#444" if i < 2 else "#ccc"
        parts.append(f'<text x="16" y="{y + big / 2 + 6}" {font} fill="{ink}">{row}</text>')
        for j, c in enumerate(cols):
            x = label + j * (big + gap)
            if row == "48px":
                for k, th in enumerate(THEMES):
                    parts.append(icon_svg(c, th, small, x + (k % 3) * 50 - 3, y + 48))
            else:
                parts.append(icon_svg(c, row, big, x, y))
    parts.append("</svg>")
    sheet = "".join(parts)
    render(sheet, out / "icon-masks.png", w)
    # 48 px at true size, one per shape, for a pixel-level look
    for c in cols:
        render(f'<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48">'
               f'{icon_svg(c, "colour", 48)}</svg>', out / f"icon-48-{c}.png", 48)
    # safe zone overlay on the raw 108 canvas
    render('<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108" viewBox="0 0 108 108">'
           + svg_body("background") + svg_body("foreground")
           + '<circle cx="54" cy="54" r="33" fill="none" stroke="#3DDC84" stroke-width="0.6"/>'
           '<rect x="18" y="18" width="72" height="72" fill="none" stroke="#fff" '
           'stroke-width="0.4" stroke-dasharray="2 2"/></svg>', out / "icon-safe-zone.png", 432)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("--res", type=Path)
    p.add_argument("--play", type=Path)
    p.add_argument("--preview", type=Path)
    a = p.parse_args()
    if not (a.res or a.play or a.preview):
        p.error("nothing to do")
    if a.res:
        build_res(a.res)
    if a.play:
        build_play(a.play)
    if a.preview:
        build_preview(a.preview)


if __name__ == "__main__":
    main()
